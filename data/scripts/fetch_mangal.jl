# Download the food webs of the Mangal database (mangal.io) to
# `FoodWebs.foodweb_cache()/mangal`, in the package's data format. A network counts as a food
# web when every interaction in it is trophic (predation, herbivory, detritivory or scavenging);
# networks mixing in parasitism, mutualism or unspecified interactions are skipped. Mangal
# interactions point from consumer to resource.
#
# Run from the repository root, optionally naming the datasets to fetch:
#     julia --project=data/scripts data/scripts/fetch_mangal.jl [havens_1992 ...]

using CSV: CSV
using DataFrames: DataFrame
using Downloads: download
using FoodWebs: FoodWebs
using JSON: JSON
using TOML: TOML

include("datapackage.jl")

const API = "https://mangal.io/api/v2"
const OUT = joinpath(FoodWebs.foodweb_cache(), "mangal")
const TROPHIC = Set(["predation", "herbivory", "detritivore", "scavenger"])
const PAGE = 1000

get_json(url) = JSON.parse(String(take!(download(url, IOBuffer()))))

# Every record of an endpoint matching `query`, a page at a time
function get_all(endpoint, query = "")
    records = Any[]
    for page in 0:typemax(Int)
        batch = get_json("$API/$endpoint?count=$PAGE&page=$page$query")
        append!(records, batch)
        length(batch) < PAGE && break
    end
    return records
end

function citation(ref)
    ref === nothing && return ""
    bib = something(get(ref, "bibtex", nothing), "")
    field(name) = (m = match(Regex("$name\\s*=\\s*\\{(.*?)\\}[,}]"), bib); m === nothing ? "" : m[1])
    parts = filter(!isempty, [field("author"), field("title"), field("journal"), field("volume"), field("pages"), string(something(get(ref, "year", nothing), ""))])
    doi = something(get(ref, "doi", nothing), "")
    return join(parts, ", ") * (isempty(doi) ? "" : " doi:$doi")
end

function fetch_network(network)
    id = network["id"]
    interactions = get_all("interaction", "&network_id=$id")
    isempty(interactions) && return nothing
    all(x -> x["type"] in TROPHIC, interactions) || return nothing
    nodes = get_all("node", "&network_id=$id")
    # node names can repeat within a network, so make them unique with the node id
    names = Dict(n["id"] => strip(n["original_name"]) for n in nodes)
    counts = Dict{String, Int}()
    foreach(n -> counts[n] = get(counts, n, 0) + 1, values(names))
    label = Dict(k => (counts[v] > 1 ? "$v ($k)" : v) for (k, v) in names)
    links = unique([(label[x["node_to"]], label[x["node_from"]]) for x in interactions])
    species = [label[n["id"]] for n in nodes]
    return species, links
end

function main(datasets)
    rm(OUT; force = true, recursive = true)
    catalog = Dict{String, Any}()
    for dataset in get_all("dataset")
        isempty(datasets) || dataset["name"] in datasets || continue
        ref = dataset["ref_id"] === nothing ? nothing : get_json("$API/reference/$(dataset["ref_id"])")
        for network in get_all("network", "&dataset_id=$(dataset["id"])")
            web = fetch_network(network)
            web === nothing && continue
            species, links = web
            id = network["name"]
            dir = mkpath(joinpath(OUT, id))
            CSV.write(joinpath(dir, "nodes.csv"), DataFrame(node = species))
            CSV.write(joinpath(dir, "trophic.links.csv"), DataFrame(resource = first.(links), consumer = last.(links)))
            catalog[id] = Dict(
                "title" => something(network["description"], id),
                "dataset" => dataset["name"],
                "species" => length(species),
                "links" => length(links),
                "citation" => citation(ref),
                "source" => "Mangal network $(network["id"]), $API/network/$(network["id"])",
                "license" => "Mangal data are released under the Creative Commons 0 waiver (per the pymangal documentation; the v2 site states no license).",
            )
            println(id, ": ", length(species), " species, ", length(links), " links")
        end
    end
    mkpath(OUT)
    open(joinpath(OUT, "catalog.toml"), "w") do io
        println(io, "# Generated by data/scripts/fetch_mangal.jl; do not edit by hand.")
        TOML.print(io, catalog; sorted = true)
    end
    write_datapackage(
        OUT; name = "mangal", title = "Food webs of the Mangal database",
        description = "Mangal networks whose interactions are all trophic, downloaded by data/scripts/fetch_mangal.jl.",
        licenses = [Dict("name" => "CC0-1.0", "path" => "https://creativecommons.org/publicdomain/zero/1.0/", "title" => "CC0 1.0 per the pymangal documentation; the v2 site states no license")],
        sources = [Dict("title" => "Mangal", "path" => API)],
    )
    return println("wrote $(length(catalog)) webs to $OUT")
end

main(Set(ARGS))
