# Download the binary food webs of the Web of Life database (www.web-of-life.es) to
# `FoodWebs.foodweb_cache()/web_of_life`, in the package's data format. Its terms allow free use
# and sharing with collaborators, with the acknowledgement "This work has used the Web of Life
# database (www.web-of-life.es)", so the webs are downloaded rather than bundled.
#
# Each network is a matrix with prey as rows and consumers as columns; a species appears as both
# a row and a column only if it is both prey and consumer.
#
# Run from the repository root:
#     julia --project=data/scripts data/scripts/fetch_web_of_life.jl

using CSV: CSV
using DataFrames: DataFrame
using Downloads: download
using FoodWebs: FoodWebs
using TOML: TOML

include("datapackage.jl")

const API = "https://www.web-of-life.es"
const OUT = joinpath(FoodWebs.foodweb_cache(), "web_of_life")
const ACKNOWLEDGEMENT = "This work has used the Web of Life database (www.web-of-life.es)."

function network_url(name)
    return "$API/map_download_fast2.php?format=csv&networks=$name&species=yes&type=&data=" *
        "&speciesrange=&interactionsrange=&searchbox=&checked="
end

# Rows of the network list whose type is "Food Webs" and whose cells are presence or absence
function binary_food_webs()
    info = CSV.read(download("$API/get_network_info.php"), DataFrame; stringtype = String)
    return filter(r -> isequal(r.network_type, "Food Webs") && isequal(r.is_weighted, 0), info)
end

function fetch_network(name, work)
    zip = download(network_url(name), joinpath(work, "$name.zip"))
    dir = mkpath(joinpath(work, name))
    run(`unzip -o -q $zip -d $dir`)
    # the first column holds the prey names, the header the consumer names
    m = CSV.read(joinpath(dir, "$name.csv"), DataFrame; stringtype = String)
    prey = String.(m[:, 1])
    consumers = String.(names(m)[2:end])
    nmissing = count(ismissing, Matrix(m[:, 2:end]))
    nmissing > 0 && @warn "$name: $nmissing empty cells, read as no link"
    links = [(prey[i], consumers[j]) for i in eachindex(prey), j in eachindex(consumers) if coalesce(m[i, j + 1], 0) != 0]
    species = unique(vcat(prey, consumers))
    # check against the species and interaction counts Web of Life gives for the network
    ref = only(eachrow(CSV.read(joinpath(dir, "references.csv"), DataFrame)))
    (length(species), length(links)) == (ref.Species, ref.Interactions) ||
        @warn "$name: $(length(species)) species and $(length(links)) links, Web of Life lists $(ref.Species) and $(ref.Interactions)"
    return species, vec(links)
end

function main()
    work = mktempdir()
    rm(OUT; force = true, recursive = true)
    catalog = Dict{String, Any}()
    for row in eachrow(binary_food_webs())
        name = row.network_name
        species, links = fetch_network(name, work)
        # FW_012 to FW_015 are parent records of the numbered webs and download without links
        isempty(links) && (println(name, ": no links, skipped"); continue)
        id = lowercase(name)
        dir = mkpath(joinpath(OUT, id))
        CSV.write(joinpath(dir, "nodes.csv"), DataFrame(node = species))
        CSV.write(joinpath(dir, "trophic.links.csv"), DataFrame(resource = first.(links), consumer = last.(links)))
        catalog[id] = Dict(
            "title" => "$name ($(row.location))",
            "species" => length(species),
            "links" => length(links),
            "citation" => row.reference,
            "source" => "Web of Life network $name, $(network_url(name)). $ACKNOWLEDGEMENT",
            "license" => "Web of Life terms: free use and sharing with collaborators, with the acknowledgement above.",
        )
        println(name, ": ", length(species), " species, ", length(links), " links")
    end
    open(joinpath(OUT, "catalog.toml"), "w") do io
        println(io, "# Generated by data/scripts/fetch_web_of_life.jl; do not edit by hand.")
        TOML.print(io, catalog; sorted = true)
    end
    write_datapackage(
        OUT; name = "web-of-life", title = "Binary food webs of the Web of Life database",
        description = "Downloaded by data/scripts/fetch_web_of_life.jl. $ACKNOWLEDGEMENT",
        licenses = [Dict("name" => "other-at", "title" => "Web of Life terms: free use and sharing with collaborators, with acknowledgement")],
        sources = [Dict("title" => "Web of Life", "path" => API)],
    )
    return println("wrote $(length(catalog)) webs to $OUT")
end

main()
