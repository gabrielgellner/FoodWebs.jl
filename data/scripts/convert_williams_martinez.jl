# Convert the seven trophic-species webs of Williams & Martinez (2000) from their `.dat` files to
# the package's data format. Each `.dat` file has the number of species `S` on its first line and
# then `S` rows of `S` characters, where `X` in row `i`, column `j` means species `j` eats
# species `i`. The files name no species, so species are named by their index.
#
# Run from the repository root with the directory holding the `.dat` files:
#     julia --project=data/scripts data/scripts/convert_williams_martinez.jl path/to/data

using TOML: TOML

include("datapackage.jl")

const OUT = joinpath(@__DIR__, "..", "williams_martinez_2000")

const COMPILATION = "Williams, R. J. & Martinez, N. D. Simple rules yield complex food webs. Nature 404, 180–183 (2000); Dunne, J. A., Williams, R. J. & Martinez, N. D. Food-web structure and network theory: the role of connectance and size. PNAS 99, 12917–12922 (2002)."

# file => (id, title, citation of the original web)
const WEBS = Dict(
    "bridgebrook.dat" => ("bridge_brook_lake", "Bridge Brook Lake", "Havens, K. Scale and structure in natural food webs. Science 257, 1107–1109 (1992)."),
    "chesapeake.dat" => ("chesapeake_bay", "Chesapeake Bay", "Baird, D. & Ulanowicz, R. E. The seasonal dynamics of the Chesapeake Bay ecosystem. Ecol. Monogr. 59, 329–364 (1989)."),
    "coachella.dat" => ("coachella_valley", "Coachella Valley", "Polis, G. A. Complex trophic interactions in deserts: an empirical critique of food-web theory. Am. Nat. 138, 123–155 (1991)."),
    "littlerock.dat" => ("little_rock_lake", "Little Rock Lake", "Martinez, N. D. Artifacts or attributes? Effects of resolution on the Little Rock Lake food web. Ecol. Monogr. 61, 367–392 (1991)."),
    "skipwith.dat" => ("skipwith_pond", "Skipwith Pond", "Warren, P. H. Spatial and temporal variation in the structure of a freshwater food web. Oikos 55, 299–311 (1989)."),
    "stmartin.dat" => ("st_martin_island", "St. Martin Island", "Goldwasser, L. & Roughgarden, J. Construction and analysis of a large Caribbean food web. Ecology 74, 1216–1233 (1993)."),
    "ythan.dat" => ("ythan_estuary", "Ythan Estuary", "Hall, S. J. & Raffaelli, D. Food-web patterns: lessons from a species-rich web. J. Anim. Ecol. 60, 823–841 (1991)."),
)

function read_dat(path)
    lines = readlines(path)
    S = parse(Int, strip(lines[1]))
    # trailing empty columns are sometimes left off a row
    rows = [rpad(rstrip(l), S, '.') for l in lines[2:(S + 1)]]
    all(length(r) == S for r in rows) || error("$path: rows longer than $S")
    return [rows[i][j] == 'X' for i in 1:S, j in 1:S]
end

function main(src)
    rm(OUT; force = true, recursive = true)
    catalog = Dict{String, Any}()
    for (file, (id, title, citation)) in WEBS
        web = read_dat(joinpath(src, file))
        S = size(web, 1)
        dir = joinpath(OUT, id)
        mkpath(dir)
        write(joinpath(dir, "nodes.csv"), "node\n" * join(string.(1:S, "\n")))
        open(joinpath(dir, "trophic.links.csv"), "w") do io
            println(io, "resource,consumer")
            for j in 1:S, i in 1:S
                web[i, j] && println(io, i, ",", j)
            end
        end
        catalog[id] = Dict(
            "title" => title,
            "species" => S,
            "links" => count(web),
            "citation" => citation,
            "source" => "Trophic-species web as compiled by $COMPILATION",
            "license" => "No license given; redistributed with citation of the original data.",
        )
    end
    open(joinpath(OUT, "catalog.toml"), "w") do io
        println(io, "# Generated by data/scripts/convert_williams_martinez.jl; do not edit by hand.")
        TOML.print(io, catalog; sorted = true)
    end
    write_datapackage(
        OUT; name = "williams-martinez-2000", title = "Trophic-species webs of Williams & Martinez (2000)",
        description = "Seven trophic-species food webs, converted by data/scripts/convert_williams_martinez.jl. Species are numbered.",
        licenses = [Dict("name" => "notspecified", "title" => "No license given; redistributed with citation of the original data")],
        sources = [Dict("title" => COMPILATION)],
    )
    return println("wrote $(length(catalog)) webs to $(normpath(OUT))")
end

main(ARGS[1])
